// All fixed website text, in English and Bangla. English pages live at /about, Bangla pages at /bn/about.
// Text typed into the admin (news, album titles, names) is shown as it was typed.

export type Lang = "en" | "bn";
export const LANGS: Lang[] = ["en", "bn"];
export type LangParams = Promise<{ lang: string }>;

export function isLang(value: string): value is Lang {
  return (LANGS as string[]).includes(value);
}

export async function getLang(params: Promise<{ lang: string }>): Promise<Lang> {
  const { lang } = await params;
  return isLang(lang) ? lang : "en";
}

// The address of a page in the given language: localePath("bn", "/about") is "/bn/about".
export function localePath(lang: Lang, path: string) {
  if (lang === "en") return path;
  return path === "/" ? "/bn" : `/bn${path}`;
}

// Shows digits in Bangla on Bangla pages: 2025 becomes ২০২৫.
export function digits(value: string | number, lang: Lang) {
  const text = String(value);
  return lang === "bn" ? text.replace(/\d/g, (d) => "০১২৩৪৫৬৭৮৯"[Number(d)]) : text;
}

// Tells search engines about the page's other language.
export function pageMetaAlternates(lang: Lang, path: string): Metadata["alternates"] {
  return { canonical: localePath(lang, path), languages: { en: path, bn: localePath("bn", path) } };
}

export function pageMeta(lang: Lang, path: string, title: string, description: string): Metadata {
  return { title: `${title} | BMMSWC`, description, alternates: pageMetaAlternates(lang, path) };
}

